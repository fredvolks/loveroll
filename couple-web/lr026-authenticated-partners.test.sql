-- Behavioral stand-in only; not created by the LR-026 migration.
-- Existing LR-026 private ranking helper drives the eligible selection.
CREATE FUNCTION lr026_auth.respond(
 p_challenge integer,p_action text,p_exclude boolean DEFAULT false
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $lr026_auth_respond$
DECLARE
  v_actor uuid := auth.uid();
  v_couple lr026_auth.couples%rowtype;
  v_old lr026_auth.challenges%rowtype;
  v_prior lr026_auth.challenges%rowtype;
  v_card integer;
  v_used integer;
  v_new_id integer;
BEGIN
  IF v_actor IS NULL THEN
    RAISE EXCEPTION 'Identité vérifiée requise';
  END IF;
  IF p_action IS NULL OR p_action NOT IN ('pass','refuse')
     OR (p_action='pass' AND p_exclude IS TRUE) THEN
    RAISE EXCEPTION 'Action de remplacement invalide';
  END IF;

  -- Lock order mirrors production: couple first, then challenge.
  SELECT c.* INTO v_couple
  FROM lr026_auth.couples c
  JOIN lr026_auth.challenges ch ON ch.couple_id=c.id
  WHERE ch.id=p_challenge FOR UPDATE OF c;
  IF NOT FOUND OR v_actor NOT IN (v_couple.partner_a,v_couple.partner_b) THEN
    RAISE EXCEPTION 'Accès au couple refusé';
  END IF;
  SELECT * INTO v_old FROM lr026_auth.challenges
  WHERE id=p_challenge FOR UPDATE;
  IF NOT FOUND OR v_old.recipient IS DISTINCT FROM v_actor THEN
    RAISE EXCEPTION 'Seul le destinataire peut répondre';
  END IF;

  SELECT * INTO v_prior FROM lr026_auth.challenges
  WHERE replaces_challenge_id=p_challenge LIMIT 1;
  IF FOUND THEN
    RETURN pg_catalog.jsonb_build_object(
       'already_processed',true,'replacement_id',v_prior.id,
       'card_id',v_prior.card_id);
  END IF;
  IF v_old.status NOT IN ('proposed','accepted') THEN
    RAISE EXCEPTION 'Défi déjà terminé ou répondu';
  END IF;

  IF p_action='pass' THEN
    SELECT pg_catalog.count(*) INTO v_used
    FROM lr026_auth.challenges c
    WHERE c.couple_id=v_old.couple_id
      AND c.recipient=v_actor AND c.status='passed'
      AND c.passed_at IS NOT NULL
      AND pg_catalog.date_trunc('month',
          c.passed_at AT TIME ZONE 'America/Toronto')
        = pg_catalog.date_trunc('month',
          pg_catalog.now() AT TIME ZONE 'America/Toronto');
    IF v_used>=v_couple.monthly_pass_limit THEN
      RAISE EXCEPTION 'Limite mensuelle de passes atteinte';
    END IF;
  END IF;

  -- Change state BEFORE selecting: exhausted repige must roll this back.
  UPDATE lr026_auth.challenges SET
    status=CASE WHEN p_action='pass' THEN 'passed' ELSE 'refused' END,
    passed_at=CASE WHEN p_action='pass' THEN pg_catalog.now()
                   ELSE passed_at END,
    refused_at=CASE WHEN p_action='refuse' THEN pg_catalog.now()
                   ELSE refused_at END
  WHERE id=v_old.id;
  IF p_action='refuse' AND p_exclude IS TRUE THEN
    INSERT INTO lr026_auth.exclusions(couple_id,category,card_id)
    VALUES(v_old.couple_id,v_old.category,v_old.card_id)
    ON CONFLICT DO NOTHING;
  END IF;

  SELECT candidate.card INTO v_card
  FROM pg_catalog.generate_series(1,3) AS candidate(card)
  WHERE candidate.card<>v_old.card_id
    AND NOT EXISTS(
      SELECT 1 FROM lr026_auth.exclusions ex
      WHERE ex.couple_id=v_old.couple_id
        AND ex.category=v_old.category AND ex.card_id=candidate.card)
    AND NOT EXISTS(
      SELECT 1 FROM lr026_auth.challenges ch
      WHERE ch.session_id=v_old.session_id AND ch.recipient=v_actor
        AND ch.category=v_old.category AND ch.card_id=candidate.card)
  ORDER BY couple_private.love_variety_rank(
     v_old.session_id,v_old.couple_id,v_old.category,candidate.card
  ) ASC, pg_catalog.random() LIMIT 1;
  IF v_card IS NULL THEN
    RAISE EXCEPTION 'Aucun autre défi admissible dans cette catégorie pour ce soir';
  END IF;

  INSERT INTO lr026_auth.challenges(
    couple_id,session_id,recipient,category,card_id,replaces_challenge_id)
  VALUES(v_old.couple_id,v_old.session_id,v_actor,v_old.category,v_card,v_old.id)
  RETURNING id INTO v_new_id;
  RETURN pg_catalog.jsonb_build_object(
    'already_processed',false,'replacement_id',v_new_id,'card_id',v_card);
END; $lr026_auth_respond$;
REVOKE ALL ON FUNCTION lr026_auth.respond(integer,text,boolean)
 FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION lr026_auth.respond(integer,text,boolean)
 TO authenticated;

-- Exercise the *actual* anonymous PostgreSQL role and ACLs.
SET LOCAL ROLE anon;
DO $lr026_anon$
DECLARE denied boolean:=false;
BEGIN
  BEGIN
    PERFORM lr026_auth.respond(100,'pass',false);
  EXCEPTION WHEN insufficient_privilege THEN denied:=true;
  END;
  IF NOT denied THEN RAISE EXCEPTION 'LR-026: anon invoked private game response'; END IF;
END; $lr026_anon$;
RESET ROLE;

-- Authenticated without a user claim must also be rejected.
SET LOCAL ROLE authenticated;
SELECT pg_catalog.set_config('request.jwt.claim.sub','',true);
DO $lr026_empty_identity$
DECLARE err text;
BEGIN
  BEGIN
    PERFORM lr026_auth.respond(100,'pass',false);
  EXCEPTION WHEN OTHERS THEN
    GET STACKED DIAGNOSTICS err=MESSAGE_TEXT;
  END;
  IF err IS DISTINCT FROM 'Identité vérifiée requise' THEN
    RAISE EXCEPTION 'LR-026: missing identity was allowed: %',err;
  END IF;
END; $lr026_empty_identity$;

-- A sees only A's challenges through genuine RLS.
SELECT pg_catalog.set_config(
 'request.jwt.claim.sub','aaaaaaaa-1111-4111-8111-aaaaaaaaaaaa',true);
DO $lr026_actor_a$
DECLARE
  first_result jsonb;
  again jsonb;
  err text;
  n integer;
  last_status text;
BEGIN
  SELECT pg_catalog.count(*) INTO n FROM lr026_auth.challenges;
  IF n<>3 THEN RAISE EXCEPTION 'LR-026: A RLS sees % rather than 3 rows',n; END IF;
  SELECT pg_catalog.count(*) INTO n FROM lr026_auth.couples;
  IF n<>1 THEN RAISE EXCEPTION 'LR-026: A cannot see own couple'; END IF;

  -- Identity never comes from the RPC parameters.
  BEGIN
    PERFORM lr026_auth.respond(200,'pass',false);
  EXCEPTION WHEN OTHERS THEN GET STACKED DIAGNOSTICS err=MESSAGE_TEXT;
  END;
  IF err IS DISTINCT FROM 'Seul le destinataire peut répondre' THEN
    RAISE EXCEPTION 'LR-026: A answered for B: %',err;
  END IF;

  -- Bypass attempts with raw SQL must be denied by actual role grants.
  BEGIN
    UPDATE lr026_auth.challenges SET status='passed' WHERE id=101;
    RAISE EXCEPTION 'LR-026: browser altered challenge via SQL';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;

  first_result := lr026_auth.respond(100,'pass',false);
  IF (first_result->>'card_id')::integer IS DISTINCT FROM 2 THEN
    RAISE EXCEPTION 'LR-026: A did not receive the unique new card: %',first_result;
  END IF;
  again := lr026_auth.respond(100,'pass',false);
  IF (again->>'already_processed')::boolean IS DISTINCT FROM true
    OR again->>'replacement_id' IS DISTINCT FROM first_result->>'replacement_id' THEN
    RAISE EXCEPTION 'LR-026: second tap created another replacement';
  END IF;

  err:=NULL;
  BEGIN
    PERFORM lr026_auth.respond(101,'pass',false);
  EXCEPTION WHEN OTHERS THEN GET STACKED DIAGNOSTICS err=MESSAGE_TEXT;
  END;
  IF err IS DISTINCT FROM 'Limite mensuelle de passes atteinte' THEN
    RAISE EXCEPTION 'LR-026: A monthly limit bypassed: %',err;
  END IF;
  SELECT status INTO last_status FROM lr026_auth.challenges WHERE id=101;
  IF last_status<>'proposed' THEN
    RAISE EXCEPTION 'LR-026: denied A pass altered a challenge';
  END IF;

  -- A can still refuse at no pass cost after reaching the monthly cap.
  PERFORM lr026_auth.respond(101,'refuse',true);
  SELECT status INTO last_status FROM lr026_auth.challenges WHERE id=101;
  IF last_status<>'refused' THEN
    RAISE EXCEPTION 'LR-026: A refusal was incorrectly blocked by pass quota';
  END IF;
END; $lr026_actor_a$;

-- Switch actor to B without closing the database transaction.
SELECT pg_catalog.set_config(
 'request.jwt.claim.sub','bbbbbbbb-1111-4111-8111-bbbbbbbbbbbb',true);
DO $lr026_actor_b$
DECLARE err text; n integer; r jsonb; state text;
BEGIN
  SELECT pg_catalog.count(*) INTO n FROM lr026_auth.challenges;
  IF n<>2 THEN RAISE EXCEPTION 'LR-026: B RLS leaked A rows (% total)',n; END IF;

  err:=NULL;
  BEGIN
    PERFORM lr026_auth.respond(102,'refuse',false);
  EXCEPTION WHEN OTHERS THEN GET STACKED DIAGNOSTICS err=MESSAGE_TEXT;
  END;
  IF err IS DISTINCT FROM 'Seul le destinataire peut répondre' THEN
    RAISE EXCEPTION 'LR-026: B answered for A: %',err;
  END IF;
  r := lr026_auth.respond(200,'pass',false);
  IF (r->>'card_id')::integer NOT IN (2,3) THEN
    RAISE EXCEPTION 'LR-026: B independent pass failed: %',r;
  END IF;
  err:=NULL;
  BEGIN
    PERFORM lr026_auth.respond(201,'pass',false);
  EXCEPTION WHEN OTHERS THEN GET STACKED DIAGNOSTICS err=MESSAGE_TEXT;
  END;
  IF err IS DISTINCT FROM 'Limite mensuelle de passes atteinte' THEN
    RAISE EXCEPTION 'LR-026: B bypassed own monthly limit: %',err;
  END IF;
  SELECT status INTO state FROM lr026_auth.challenges WHERE id=201;
  IF state<>'proposed' THEN
    RAISE EXCEPTION 'LR-026: denied B pass modified card';
  END IF;
END; $lr026_actor_b$;

-- Outsider with an authenticated role must still see zero rows and
-- cannot use the SECURITY DEFINER function to reach the couple.
SELECT pg_catalog.set_config(
 'request.jwt.claim.sub','cccccccc-1111-4111-8111-cccccccccccc',true);
DO $lr026_outsider$
DECLARE err text; n integer;
BEGIN
  SELECT pg_catalog.count(*) INTO n FROM lr026_auth.challenges;
  IF n<>0 THEN RAISE EXCEPTION 'LR-026: outsider sees private challenges'; END IF;
  SELECT pg_catalog.count(*) INTO n FROM lr026_auth.couples;
  IF n<>0 THEN RAISE EXCEPTION 'LR-026: outsider sees private couple'; END IF;
  BEGIN
    PERFORM lr026_auth.respond(100,'pass',false);
  EXCEPTION WHEN OTHERS THEN GET STACKED DIAGNOSTICS err=MESSAGE_TEXT;
  END;
  IF err IS DISTINCT FROM 'Accès au couple refusé' THEN
    RAISE EXCEPTION 'LR-026: outsider accessed response RPC: %',err;
  END IF;
END; $lr026_outsider$;

