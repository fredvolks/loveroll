    PERFORM lr026_auth.respond(102,'refuse',true);
  EXCEPTION WHEN OTHERS THEN GET STACKED DIAGNOSTICS err=MESSAGE_TEXT;
  END;
  IF err IS DISTINCT FROM
    'Aucun autre défi admissible dans cette catégorie pour ce soir' THEN
