  IF state<>'proposed' THEN
    RAISE EXCEPTION 'LR-026: failed redraw left challenge refused';
  END IF;
  SELECT pg_catalog.count(*) INTO n FROM lr026_auth.challenges
  WHERE replaces_challenge_id=102;
  IF n<>0 THEN
    RAISE EXCEPTION 'LR-026: failed redraw committed a replacement';
  END IF;
END; $lr026_exhausted$;

