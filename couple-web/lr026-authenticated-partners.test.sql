-- LR-026: two-partner / outsider access tests on disposable PostgreSQL 17.
-- This is NOT real Supabase Auth or the full production Passer/Refuser RPC:
-- auth.uid() is a local claim simulator. The actual PostgreSQL roles,
-- RLS policies, SECURITY DEFINER, ACLs and LR-026 ranking helper ARE executed.
-- Never run this fixture against a hosted database. All changes roll back.
