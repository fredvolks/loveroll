CREATE SCHEMA auth;
CREATE SCHEMA couple_private;
DO $$BEGIN CREATE ROLE authenticated NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END$$;
DO $$BEGIN CREATE ROLE anon NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END$$;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
 SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid;
$$;
CREATE TABLE auth.users(id uuid PRIMARY KEY);
CREATE TABLE public.couples(id uuid PRIMARY KEY);
CREATE TABLE public.couple_members(
 couple_id uuid REFERENCES public.couples(id),user_id uuid REFERENCES auth.users(id),
 PRIMARY KEY(couple_id,user_id));
CREATE FUNCTION couple_private.is_member(c uuid) RETURNS boolean LANGUAGE sql STABLE AS $$
 SELECT EXISTS(SELECT 1 FROM public.couple_members WHERE couple_id=c AND user_id=auth.uid());
$$;
CREATE FUNCTION public.love_require_verified_identity()
RETURNS void LANGUAGE plpgsql AS $$
BEGIN IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Login required' USING errcode='42501';END IF;END
$$;
CREATE TABLE public.couple_sessions(
 id uuid PRIMARY KEY,couple_id uuid NOT NULL REFERENCES public.couples(id),finished_at timestamptz);
CREATE TABLE public.couple_challenges(
 id uuid PRIMARY KEY,couple_id uuid NOT NULL REFERENCES public.couples(id),
 session_id uuid NOT NULL REFERENCES public.couple_sessions(id),
 offered_by uuid REFERENCES auth.users(id),recipient uuid REFERENCES auth.users(id),
 status text NOT NULL DEFAULT 'proposed',
 card_description text NOT NULL DEFAULT 'Défi original : découvrir ensemble',
 card_timer_minutes smallint DEFAULT 7);
CREATE TABLE public.couple_events(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 couple_id uuid,actor_id uuid,event_type text,title text);
