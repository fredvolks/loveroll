-- LR-026: quota/refusal/idempotency test harness on DISPOSABLE PostgreSQL.
-- This is a behavioral SIMULATION of the currently inspected LR-015/016
-- response rules. It is not a test of the complete production RPC or
-- authenticated Supabase RLS: both require a separate real A/B staging run.
-- The only production component executed here is love_variety_rank.
BEGIN;

CREATE TEMP TABLE lr026_response_cases (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  couple_id uuid NOT NULL,
  session_id uuid NOT NULL,
  recipient uuid NOT NULL,
  category text NOT NULL,
  card_id integer NOT NULL,
  status text NOT NULL DEFAULT 'proposed',
  passed_at timestamptz,
  refused_at timestamptz
) ON COMMIT DROP;

CREATE TEMP TABLE lr026_response_exclusions (
  couple_id uuid NOT NULL,
  cycle_number integer NOT NULL,
  category text NOT NULL,
  card_id integer NOT NULL,
  PRIMARY KEY (couple_id,cycle_number,category,card_id)
) ON COMMIT DROP;

CREATE TEMP TABLE lr026_response_links (
  origin_id integer PRIMARY KEY,
  replacement_id integer NOT NULL,
  action text NOT NULL,
  excluded boolean NOT NULL
) ON COMMIT DROP;

CREATE FUNCTION pg_temp.lr026_simulated_respond(
  p_origin integer, p_actor uuid, p_action text,
  p_exclude boolean, p_monthly_limit integer
) RETURNS jsonb LANGUAGE plpgsql AS $lr026_sim$
DECLARE
  old_row lr026_response_cases%rowtype;
  earlier lr026_response_links%rowtype;
  v_pass_count integer;
  v_card integer;
  v_replacement integer;
  v_cycle integer := 1;
BEGIN
  IF p_action IS NULL OR p_action NOT IN ('pass','refuse')
      OR (p_action='pass' AND p_exclude IS TRUE) THEN
    RAISE EXCEPTION 'Action de remplacement invalide';
  END IF;

  SELECT * INTO old_row FROM lr026_response_cases
  WHERE id=p_origin FOR UPDATE;
  IF NOT FOUND OR old_row.recipient IS DISTINCT FROM p_actor THEN
    RAISE EXCEPTION 'Seul le destinataire peut répondre';
  END IF;

  SELECT * INTO earlier FROM lr026_response_links
  WHERE origin_id=p_origin;
  IF FOUND THEN
    RETURN pg_catalog.jsonb_build_object(
      'already_processed',true,
      'replacement_id',earlier.replacement_id);
  END IF;

  IF old_row.status NOT IN ('proposed','accepted') THEN
    RAISE EXCEPTION 'Défi déjà terminé ou répondu';
  END IF;

  IF p_action='pass' THEN
    SELECT pg_catalog.count(*) INTO v_pass_count
    FROM lr026_response_cases c
    WHERE c.couple_id=old_row.couple_id
      AND c.recipient=old_row.recipient
      AND c.status='passed' AND c.passed_at IS NOT NULL
      AND pg_catalog.date_trunc(
        'month',c.passed_at AT TIME ZONE 'America/Toronto')
        = pg_catalog.date_trunc(
          'month',pg_catalog.now() AT TIME ZONE 'America/Toronto');
    IF v_pass_count>=p_monthly_limit THEN
      RAISE EXCEPTION 'Limite mensuelle de passes atteinte';
    END IF;
  END IF;

  UPDATE lr026_response_cases SET
    status=CASE WHEN p_action='pass' THEN 'passed' ELSE 'refused' END,
    passed_at=CASE WHEN p_action='pass' THEN pg_catalog.now()
      ELSE passed_at END,
    refused_at=CASE WHEN p_action='refuse' THEN pg_catalog.now()
      ELSE refused_at END
  WHERE id=p_origin;

  IF p_action='refuse' AND p_exclude IS TRUE THEN
    INSERT INTO lr026_response_exclusions(
      couple_id,cycle_number,category,card_id)
    VALUES(old_row.couple_id,v_cycle,old_row.category,old_row.card_id)
    ON CONFLICT DO NOTHING;
  END IF;

  -- Mirrors the eligible-set-before-ORDER-BY structure of the real RPC.
  -- Only card IDs 1-3 are active in this small synthetic fixture.
  SELECT candidate.card INTO v_card
  FROM pg_catalog.generate_series(1,3) AS candidate(card)
  WHERE NOT EXISTS (
    SELECT 1 FROM lr026_response_exclusions ex
    WHERE ex.couple_id=old_row.couple_id
      AND ex.cycle_number=v_cycle
      AND ex.category=old_row.category AND ex.card_id=candidate.card
  )
  AND NOT EXISTS (
    SELECT 1 FROM lr026_response_cases used
    WHERE used.session_id=old_row.session_id
      AND used.recipient=old_row.recipient
      AND used.category=old_row.category AND used.card_id=candidate.card
  )
  ORDER BY couple_private.love_variety_rank(
    old_row.session_id,old_row.couple_id,old_row.category,candidate.card
  ) ASC,pg_catalog.random()
  LIMIT 1;

  IF v_card IS NULL THEN
    RAISE EXCEPTION 'Aucun autre défi admissible dans cette catégorie pour ce soir';
  END IF;

  INSERT INTO lr026_response_cases(
    couple_id,session_id,recipient,category,card_id)
  VALUES(old_row.couple_id,old_row.session_id,
         old_row.recipient,old_row.category,v_card)
  RETURNING id INTO v_replacement;

  INSERT INTO lr026_response_links(origin_id,replacement_id,action,excluded)
  VALUES(p_origin,v_replacement,p_action,
         p_action='refuse' AND p_exclude IS TRUE);

  RETURN pg_catalog.jsonb_build_object(
    'already_processed',false,'replacement_id',v_replacement,
    'card_id',v_card);
END; $lr026_sim$;

-- Test identities and sessions are synthetic and unrelated to real members.
INSERT INTO lr026_response_cases(
  id,couple_id,session_id,recipient,category,card_id)
VALUES
 (10,'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',
      '11111111-1111-4111-8111-111111111111',
      'aaaaaaaa-1111-4111-8111-aaaaaaaaaaaa','SENSUEL',1),
 (11,'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',
      '22222222-2222-4222-8222-222222222222',
      'aaaaaaaa-1111-4111-8111-aaaaaaaaaaaa','SENSUEL',1),
 (12,'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',
      '33333333-3333-4333-8333-333333333333',
      'aaaaaaaa-1111-4111-8111-aaaaaaaaaaaa','SENSUEL',1),
 (13,'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',
      '44444444-4444-4444-8444-444444444444',
      'bbbbbbbb-1111-4111-8111-bbbbbbbbbbbb','SENSUEL',1);

DO $lr026_response_assert$
DECLARE
  actor_a uuid := 'aaaaaaaa-1111-4111-8111-aaaaaaaaaaaa';
  actor_b uuid := 'bbbbbbbb-1111-4111-8111-bbbbbbbbbbbb';
  first_result jsonb;
  second_result jsonb;
  refusal_result jsonb;
  denial text;
  status_now text;
  links_before integer;
BEGIN
  -- A first pass is legal, and variety chooses the unrelated card 2
  -- over custom near-duplicate card 3 in the seeded original session.
  first_result := pg_temp.lr026_simulated_respond(10,actor_a,'pass',false,1);
  IF (first_result->>'card_id')::integer IS DISTINCT FROM 2 THEN
    RAISE EXCEPTION 'LR-026: first pass did not prefer fresh card 2: %',
      first_result;
  END IF;

  -- Repeated tap must not spend a second pass or create another card.
  second_result := pg_temp.lr026_simulated_respond(10,actor_a,'pass',false,1);
  IF (second_result->>'already_processed')::boolean IS DISTINCT FROM true
     OR (second_result->>'replacement_id') IS DISTINCT FROM
        (first_result->>'replacement_id') THEN
    RAISE EXCEPTION 'LR-026: repeated tap was not idempotent';
  END IF;
  IF (SELECT pg_catalog.count(*) FROM lr026_response_links) <> 1 THEN
    RAISE EXCEPTION 'LR-026: duplicate response link was created';
  END IF;

  -- One pass per month: another pass must fail without touching status.
  denial := NULL;
  BEGIN
    PERFORM pg_temp.lr026_simulated_respond(11,actor_a,'pass',false,1);
  EXCEPTION WHEN OTHERS THEN
    GET STACKED DIAGNOSTICS denial = MESSAGE_TEXT;
  END;
  IF denial IS DISTINCT FROM 'Limite mensuelle de passes atteinte' THEN
    RAISE EXCEPTION 'LR-026: monthly pass limit not enforced: %',denial;
  END IF;
  SELECT status INTO status_now FROM lr026_response_cases WHERE id=11;
  IF status_now <> 'proposed' THEN
    RAISE EXCEPTION 'LR-026: denied pass changed challenge status';
  END IF;

  -- Refusal is NOT capped by the monthly pass quota; optional exclusion
  -- must be scoped to the right couple/category/cycle.
  refusal_result := pg_temp.lr026_simulated_respond(
    11,actor_a,'refuse',true,1);
  IF (refusal_result->>'card_id')::integer NOT IN (2,3) THEN
    RAISE EXCEPTION 'LR-026: refusal replacement not valid: %',refusal_result;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM lr026_response_exclusions
    WHERE couple_id='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'
      AND category='SENSUEL' AND card_id=1 AND cycle_number=1
  ) THEN
    RAISE EXCEPTION 'LR-026: refusal exclusion not preserved';
  END IF;

  -- An invalid pass+exclude action must be rejected even when a card exists.
  denial := NULL;
  BEGIN
    PERFORM pg_temp.lr026_simulated_respond(12,actor_a,'pass',true,3);
  EXCEPTION WHEN OTHERS THEN
    GET STACKED DIAGNOSTICS denial = MESSAGE_TEXT;
  END;
  IF denial IS DISTINCT FROM 'Action de remplacement invalide' THEN
    RAISE EXCEPTION 'LR-026: pass+exclude was incorrectly accepted: %',denial;
  END IF;

  -- Explicitly exhaust all remaining candidates before a valid response.
  INSERT INTO lr026_response_exclusions(
    couple_id,cycle_number,category,card_id)
  VALUES
    ('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',1,'SENSUEL',2),
    ('aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',1,'SENSUEL',3);
  SELECT pg_catalog.count(*) INTO links_before FROM lr026_response_links;

  denial := NULL;
  BEGIN
    PERFORM pg_temp.lr026_simulated_respond(12,actor_a,'pass',false,3);
  EXCEPTION WHEN OTHERS THEN
    GET STACKED DIAGNOSTICS denial = MESSAGE_TEXT;
  END;
  IF denial IS DISTINCT FROM
      'Aucun autre défi admissible dans cette catégorie pour ce soir' THEN
    RAISE EXCEPTION 'LR-026: exhausted pool failure changed: %',denial;
  END IF;
  SELECT status INTO status_now FROM lr026_response_cases WHERE id=12;
  IF status_now <> 'proposed'
     OR (SELECT pg_catalog.count(*) FROM lr026_response_links)<>links_before
     OR (SELECT pg_catalog.count(*) FROM lr026_response_cases
         WHERE recipient=actor_a AND status='passed')<>1 THEN
    RAISE EXCEPTION 'LR-026: exhausted redraw spent a pass or changed a card';
  END IF;

  -- Only the recipient can answer; no cross-partner action.
  denial := NULL;
  BEGIN
    PERFORM pg_temp.lr026_simulated_respond(13,actor_a,'refuse',false,3);
  EXCEPTION WHEN OTHERS THEN
    GET STACKED DIAGNOSTICS denial = MESSAGE_TEXT;
  END;
  IF denial IS DISTINCT FROM 'Seul le destinataire peut répondre' THEN
    RAISE EXCEPTION 'LR-026: one partner answered for the other: %',denial;
  END IF;
  SELECT status INTO status_now FROM lr026_response_cases WHERE id=13;
  IF status_now <> 'proposed' THEN
    RAISE EXCEPTION 'LR-026: unauthorized response modified partner card';
  END IF;
END; $lr026_response_assert$;
ROLLBACK;
